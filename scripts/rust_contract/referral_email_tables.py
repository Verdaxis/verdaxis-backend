"""Generate the Unicode and IDNA data tables used by the Rust EmailStr port.

Run in the pinned Python environment (3.12 with idna==3.18), never from a
development shell, so the tables describe the oracle that production runs:

    venv/bin/python -m scripts.rust_contract.referral_email_tables > rs/read/src/crud/referrals/email_tables.rs

The output is Rust source. It contains only Unicode properties (from the
interpreter's `unicodedata`) and the published IDNA tables (from the `idna`
package), so a change in either dependency shows up as a diff in this file.
Run `cargo fmt` after regenerating: the generator ends with a blank line that
rustfmt removes.
"""
import sys
import unicodedata

import idna
from idna import idnadata, uts46data

MAX_CODE_POINT = 0x10FFFF
# Rust `char` cannot hold a surrogate, so tables never need to answer for one.
SURROGATES = range(0xD800, 0xE000)
SURROGATE = 'surrogate'
BIDI_CLASSES = ['', 'L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
                'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI']


def rust_string(text):
    """A Rust string literal using escapes for everything outside printable ASCII."""
    parts = []
    for character in text:
        code = ord(character)
        if character in '"\\':
            parts.append('\\' + character)
        elif 0x20 <= code < 0x7F:
            parts.append(character)
        else:
            parts.append(f'\\u{{{code:x}}}')
    return '"' + ''.join(parts) + '"'


def runs(function):
    """Merge consecutive code points that share one value into inclusive ranges."""
    ranges = []
    start, value = 0, function(0)
    for code in range(1, MAX_CODE_POINT + 2):
        current = function(code) if code <= MAX_CODE_POINT else object()
        if current != value:
            ranges.append((start, code - 1, value))
            start, value = code, current
    return ranges


def emit_array(name, element_type, rows, per_line=4):
    print('#[rustfmt::skip]')
    print(f'pub static {name}: &[{element_type}] = &[')
    for index in range(0, len(rows), per_line):
        print('    ' + ' '.join(row + ',' for row in rows[index:index + per_line]))
    print('];')
    print()


def emit_ranges(name, ranges):
    emit_array(name, '(u32, u32)', [f'(0x{start:x}, 0x{end:x})' for start, end in ranges], per_line=6)


def intrange_pairs(encoded):
    return [(value >> 32, (value & 0xFFFFFFFF) - 1) for value in encoded]


def main():
    assert unicodedata.unidata_version, 'unidata version is required'
    print('//! Generated by `scripts/rust_contract/referral_email_tables.py`. Do not edit by hand.')
    print(f'//! Unicode properties: Python {sys.version.split()[0]} unicodedata {unicodedata.unidata_version}.')
    print(f'//! IDNA tables: idna {idna.__version__} (data version {idnadata.__version__}).')
    print('//! Ranges are inclusive. Lookups use binary search; see `email.rs`.')
    print()

    # Surrogates get their own sentinel value so no run spans the gap Rust cannot hold.
    categories = runs(lambda code: SURROGATE if code in SURROGATES else unicodedata.category(chr(code)))
    emit_array('GENERAL_CATEGORY', '(u32, u32, [u8; 2])',
               [f'(0x{start:x}, 0x{end:x}, *b"{value}")' for start, end, value in categories if value != SURROGATE])

    named = []
    for code in range(MAX_CODE_POINT + 1):
        if code in SURROGATES or unicodedata.category(chr(code))[0] in 'LNPS':
            continue
        name = unicodedata.name(chr(code), None)
        if name is not None:
            named.append((code, name))
    emit_array('CHARACTER_NAMES', '(u32, &str)', [f'(0x{code:x}, {rust_string(name)})' for code, name in named], per_line=2)

    # `_combining_class` treats a code point without a name as unknown. The set is not
    # only the unassigned and private-use code points: some scripts (Tangut, Nushu,
    # Khitan) have no name in this interpreter either.
    unnamed = runs(lambda code: code not in SURROGATES and unicodedata.name(chr(code), None) is None)
    emit_ranges('UNNAMED', [(start, end) for start, end, value in unnamed if value])

    bidi = runs(lambda code: SURROGATE if code in SURROGATES else unicodedata.bidirectional(chr(code)))
    emit_array('BIDIRECTIONAL', '(u32, u32, u8)',
               [f'(0x{start:x}, 0x{end:x}, {BIDI_CLASSES.index(value)})' for start, end, value in bidi if value != SURROGATE],
               per_line=5)
    print('#[rustfmt::skip]')
    print('pub static BIDIRECTIONAL_CLASSES: &[&str] = &[' + ', '.join(rust_string(value) for value in BIDI_CLASSES) + '];')
    print()

    virama = [code for code in range(MAX_CODE_POINT + 1) if unicodedata.combining(chr(code)) == 9]
    emit_array('VIRAMA', 'u32', [f'0x{code:x}' for code in virama], per_line=8)
    dot_decompositions = [code for code in range(MAX_CODE_POINT + 1)
                          if '002E' in unicodedata.decomposition(chr(code)).split(' ')]
    emit_array('DECOMPOSES_WITH_DOT', 'u32', [f'0x{code:x}' for code in dot_decompositions], per_line=8)

    alphanumeric = runs(lambda code: chr(code).isalnum())
    emit_ranges('ALPHANUMERIC', [(start, end) for start, end, value in alphanumeric if value and start not in SURROGATES])
    spaces = runs(lambda code: chr(code).isspace())
    emit_ranges('WHITESPACE', [(start, end) for start, end, value in spaces if value])

    for script in ('Greek', 'Han', 'Hebrew', 'Hiragana', 'Katakana'):
        emit_ranges(f'SCRIPT_{script.upper()}', intrange_pairs(idnadata.scripts[script]))
    for joining in sorted(idnadata.joining_types):
        emit_ranges(f'JOINING_{joining}', intrange_pairs(idnadata.joining_types[joining]))
    print('#[rustfmt::skip]')
    print('pub static JOINING_TYPES: &[(char, &[(u32, u32)])] = &[' + ', '.join(
        f"('{joining}', JOINING_{joining})" for joining in sorted(idnadata.joining_types)) + '];')
    print()
    for kind in ('PVALID', 'CONTEXTJ', 'CONTEXTO'):
        emit_ranges(f'IDNA_{kind}', intrange_pairs(idnadata.codepoint_classes[kind]))

    emit_array('UTS46_STARTS', 'u32', [f'0x{start:x}' for start in uts46data.uts46_starts], per_line=10)
    statuses = ''.join(chr(status) for status in uts46data.uts46_statuses)
    assert statuses.isascii() and statuses.isalnum(), 'status codes are single ASCII letters or digits'
    print('#[rustfmt::skip]')
    print('pub static UTS46_STATUSES: &[u8] = b"\\')
    for index in range(0, len(statuses), 96):
        print('    ' + statuses[index:index + 96] + '\\')
    print('    ";')
    print()
    emit_array('UTS46_REPLACEMENTS', 'Option<&str>',
               ['None' if value is None else f'Some({rust_string(value)})' for value in uts46data.uts46_replacements],
               per_line=4)


if __name__ == '__main__':
    main()
