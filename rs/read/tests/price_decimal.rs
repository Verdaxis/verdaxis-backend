use verdaxis_read::market::amount::{Amount, trade_total};

#[test]
fn exact_sql_product_gets_python_context_without_normalizing_scale() {
    for (exact, expected) in [
        ("2.0000", "2.0000"),
        (
            "2.000000000000000000000000000",
            "2.000000000000000000000000000",
        ),
        (
            "2.00000000000000000000000000000000",
            "2.000000000000000000000000000",
        ),
        (
            "1.2345678901234567890123456785",
            "1.234567890123456789012345678",
        ),
        (
            "1.2345678901234567890123456795",
            "1.234567890123456789012345680",
        ),
        (
            "9.9999999999999999999999999995",
            "10.00000000000000000000000000",
        ),
        ("0.00000001", "1E-8"),
        ("0.00000000", "0E-8"),
        (
            "123456789012345678901234567890",
            "1.234567890123456789012345679E+29",
        ),
    ] {
        assert_eq!(
            Amount::parse(&trade_total(exact).unwrap())
                .unwrap()
                .compare(&Amount::parse(expected).unwrap()),
            std::cmp::Ordering::Equal,
            "{exact}"
        );
    }
}
